// sweeps every speed level through the channel simulator and writes docs/curves.md:
// codeword error rate, the receiver's own SNR estimate, and net throughput per point

use ofm_core::chansim::{Channel, ChannelConfig};
use ofm_core::modem::{
    build_frame, frame_samples, lead_in, Chunk, Header, Kind, Profile, Receiver, RxEvent, FS,
    LEVELS,
};
use std::fmt::Write as _;

const FRAMES: usize = 12;
const CHUNKS: usize = 6;
const TXDELAY_MS: u32 = 200;

struct Point {
    chan_snr: f32,
    est_snr: f32,
    cer: f32,
    net_bps: f32,
}

fn sweep(profile: Profile, level: u8, path: &ChannelConfig) -> Vec<Point> {
    let lv = LEVELS[level as usize];
    let cap = Chunk::capacity(lv.info_bytes());
    let mut points = Vec::new();
    for snr in (-3..=36).step_by(3) {
        let mut cfg = path.clone();
        cfg.snr_db = Some(snr as f32);
        cfg.clock_ppm = 100.0;
        cfg.seed = (level as u64) << 16 | snr as u64;
        let mut chan = Channel::new(cfg);
        let (mut good, mut est, mut heard) = (0usize, 0.0f32, 0usize);
        for f in 0..FRAMES {
            let chunks: Vec<Chunk> = (0..CHUNKS)
                .map(|i| Chunk {
                    offset: (i * cap) as u32,
                    data: (0..cap).map(|j| (f * 17 + i * 31 + j * 7) as u8).collect(),
                })
                .collect();
            let mut h = Header::new(Kind::Data, profile, "N0CALL", "W1AW");
            h.level = level;
            let mut audio = lead_in(TXDELAY_MS);
            audio.extend(build_frame(&h, &chunks, 9.0));
            audio.extend(std::iter::repeat_n(0.0, FS / 2));
            let mut rx = Receiver::new(profile);
            for block in chan.transmit(&audio).chunks(480) {
                for ev in rx.push(block) {
                    if let RxEvent::Frame(r) = ev {
                        heard += 1;
                        est += r.snr_db;
                        good += r
                            .chunks
                            .iter()
                            .zip(&chunks)
                            .filter(|(a, b)| a.as_ref() == Some(b))
                            .count();
                    }
                }
            }
        }
        let sent = FRAMES * CHUNKS;
        let airtime = (frame_samples(profile, &lv, CHUNKS) + FS * TXDELAY_MS as usize / 1000)
            as f32
            / FS as f32;
        points.push(Point {
            chan_snr: snr as f32,
            est_snr: if heard > 0 {
                est / heard as f32
            } else {
                f32::NAN
            },
            cer: 1.0 - good as f32 / sent as f32,
            net_bps: good as f32 * cap as f32 * 8.0 / (FRAMES as f32 * airtime),
        });
    }
    points
}

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "docs/curves.md".into());
    let mut md = String::new();
    writeln!(md, "# Speed level curves\n").unwrap();
    writeln!(
        md,
        "Generated by `cargo run --release -p ofm-core --bin ofm-curves`. Each point is {FRAMES} frames of \
         {CHUNKS} codewords through the channel simulator with a +100 ppm clock offset, {TXDELAY_MS} ms \
         TXDELAY and a 9 dB peak-to-average limit. \"Channel SNR\" is the simulator's setting (signal over \
         white noise across 0-24 kHz); \"est SNR\" is what the receiver reports, which is what rate \
         adaptation compares with each level's threshold. CER is the codeword error rate. Net bps counts \
         delivered payload bytes over the airtime of one frame including TXDELAY, without turnaround.\n"
    )
    .unwrap();
    for (profile, path) in [
        (Profile::Narrow, ChannelConfig::narrow()),
        (Profile::Wide, ChannelConfig::wide()),
    ] {
        let results: Vec<(u8, Vec<Point>)> = std::thread::scope(|s| {
            let handles: Vec<_> = (0..LEVELS.len() as u8)
                .map(|level| {
                    let path = path.clone();
                    s.spawn(move || (level, sweep(profile, level, &path)))
                })
                .collect();
            handles.into_iter().map(|h| h.join().unwrap()).collect()
        });
        writeln!(md, "## {}\n", profile.name()).unwrap();
        for (level, points) in results {
            let lv = LEVELS[level as usize];
            writeln!(
                md,
                "### Level {level}: {}, {:.0} bps raw, threshold {} dB\n",
                lv.describe(),
                lv.bps(profile),
                lv.min_snr_db
            )
            .unwrap();
            writeln!(
                md,
                "| Channel SNR (dB) | Est SNR (dB) | CER | Net bps |\n|---:|---:|---:|---:|"
            )
            .unwrap();
            for p in points {
                writeln!(
                    md,
                    "| {:.0} | {:.1} | {:.3} | {:.0} |",
                    p.chan_snr, p.est_snr, p.cer, p.net_bps
                )
                .unwrap();
            }
            md.push('\n');
        }
    }
    std::fs::write(&out, md).expect("writing curves");
    println!("wrote {out}");
}
